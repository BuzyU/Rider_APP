class VoiceBudgetSimulationTest {

    data class CodecScenario(
        val name: String,
        val udpPayloadBytes: Int,
        val isVoice: Boolean = true
    ) {
        val ipBytes: Int = udpPayloadBytes + 28 // 20 bytes IPv4 + 8 bytes UDP
        val ipBits: Int = ipBytes * 8

        fun airtimePerFrameMs(phyRateMbps: Double): Double {
            val txSec = (180e-6) + (ipBits.toDouble() / (phyRateMbps * 1_000_000.0))
            return txSec * 1000.0
        }

        fun totalAirtimeMs(phyRateMbps: Double, copies: Int): Double {
            return airtimePerFrameMs(phyRateMbps) * copies
        }

        fun channelOccupancyPct(phyRateMbps: Double, copies: Int): Double {
            return (totalAirtimeMs(phyRateMbps, copies) / 20.0) * 100.0
        }
    }

    @Test
    fun airtimeBudgetSimulation_satisfiesChannelOccupancyConstraints() {
        val scenarios = listOf(
            CodecScenario("v3 PCM (747 B)", 747),
            CodecScenario("v3 Opus 16k (147 B)", 147),
            CodecScenario("v4 Opus 16k (69 B)", 69),
            CodecScenario("v4 Opus 12k (59 B)", 59),
            CodecScenario("v4 Opus 24k (89 B)", 89),
            CodecScenario("v4 DTX marker (30 B)", 30, isVoice = false),
            CodecScenario("v4 BYE (29 B)", 29, isVoice = false)
        )

        val rates = listOf(1.0, 2.0, 6.5, 13.0, 65.0)

        val v4Opus16k = scenarios.first { it.name.startsWith("v4 Opus 16k") }
        val v3Pcm = scenarios.first { it.name.startsWith("v3 PCM") }

        // Assert that v4 + Opus 16k at 6.5 Mbit/s with suppression (5 copies) uses < 2 ms airtime (< 10% channel occupancy)
        val v4Opus16kAirtime6_5 = v4Opus16k.totalAirtimeMs(6.5, 5)
        val v4Opus16kOccupancy6_5 = v4Opus16k.channelOccupancyPct(6.5, 5)
        assertTrue("v4 Opus 16k at 6.5 Mbit/s with suppression must use < 2 ms airtime (got $v4Opus16kAirtime6_5 ms)", v4Opus16kAirtime6_5 < 2.0)
        assertTrue("v4 Opus 16k at 6.5 Mbit/s with suppression must use < 10% channel occupancy (got $v4Opus16kOccupancy6_5 %)", v4Opus16kOccupancy6_5 < 10.0)

        // Assert that v3 PCM at 1 Mbit/s without suppression (18 copies) is > 20 ms (> 100% channel occupancy, failing on a single speaker)
        val v3PcmAirtime1_0 = v3Pcm.totalAirtimeMs(1.0, 18)
        val v3PcmOccupancy1_0 = v3Pcm.channelOccupancyPct(1.0, 18)
        assertTrue("v3 PCM at 1 Mbit/s without suppression must be > 20 ms airtime (got $v3PcmAirtime1_0 ms)", v3PcmAirtime1_0 > 20.0)
        assertTrue("v3 PCM at 1 Mbit/s without suppression must be > 100% channel occupancy (got $v3PcmOccupancy1_0 %)", v3PcmOccupancy1_0 > 100.0)

        // Generate markdown report table
        val md = buildString {
            appendLine("# Round 9 Voice Budget and Latency Simulation Report")
            appendLine()
            appendLine("Generated by `VoiceBudgetSimulationTest` at HEAD.")
            appendLine()
            appendLine("## 1. Frame Size & Airtime Model")
            appendLine("Model: `airtime = 180 µs + (IP bits / PHY rate)`. IP framing: IPv4 (20 B) + UDP (8 B) = 28 B overhead.")
            appendLine()
            appendLine("| Format | UDP Payload | IP Bytes | IP kbit/s @ 50 fps |")
            appendLine("|---|---|---|---|")
            for (s in scenarios) {
                val kbitPerSec = (s.ipBits * 50) / 1000.0
                appendLine("| ${s.name} | ${s.udpPayloadBytes} B | ${s.ipBytes} B | ${String.format(Locale.US, "%.1f", kbitPerSec)} |")
            }
            appendLine()
            appendLine("## 2. Airtime & Channel Occupancy per 20 ms Frame Period")
            appendLine()
            appendLine("| Format | Copies | 1.0 Mbit/s | 2.0 Mbit/s | 6.5 Mbit/s | 13.0 Mbit/s | 65.0 Mbit/s |")
            appendLine("|---|---|---|---|---|---|---|")
            for (s in scenarios) {
                for (copies in listOf(18, 5)) {
                    val label = if (copies == 18) "×18 (unsuppressed)" else "×5 (suppressed)"
                    val cells = rates.map { r ->
                        val ms = s.totalAirtimeMs(r, copies)
                        val pct = s.channelOccupancyPct(r, copies)
                        "${String.format(Locale.US, "%.1f", ms)} ms (${String.format(Locale.US, "%.0f", pct)}%)"
                    }.joinToString(" | ")
                    appendLine("| ${s.name} | $label | $cells |")
                }
            }
            appendLine()
            appendLine("## 3. Findings & Validation Summary")
            appendLine("- **Target Goal (≤ 100 B UDP voice payload):** v4 Opus 16k is **69 B** (meeting target with 31 B margin).")
            appendLine("- **Relay Suppression Leverage:** In a 6-node clique, packet copies per voice frame drop from 18–25 down to **5**.")
            appendLine("- **Channel Occupancy at Edge of Range (6.5 Mbit/s):** Drops from **102%** (v3 PCM unsuppressed) down to **7.5%** (v4 Opus 16k suppressed), restoring voice headroom on weak links.")
            appendLine("- **Standing Latency Elimination:** The 16-frame burst jump fix eliminates the standing ~320 ms queue after Wi-Fi stalls.")
        }

        val reportFile = File("../docs/reports/round9-voice-budget.md")
        reportFile.parentFile?.mkdirs()
        reportFile.writeText(md)
    }

    @Test
    fun jitterBufferSimulation_zeroLoss_nominalDepthMaintained() {
        var now = 10_000L
        val clock = { now }
        val jb = SourceJitterBuffer("peer", clock = clock)

        var audioCount = 0
        var concealedCount = 0

        for (seq in 1..100) {
            jb.enqueue(seq, ByteArray(MeshConfig.BYTES_PER_FRAME))
            val frame = jb.pollFrame()
            when (frame) {
                is PlayoutFrame.Audio -> audioCount++
                is PlayoutFrame.Concealed -> concealedCount++
                else -> {}
            }
            now += 20L
        }

        // Playout starts after initial 3-frame target buffer depth
        assertTrue("Audio frames played should be ~97 out of 100 (got $audioCount)", audioCount in 96..98)
        assertEquals("Concealed frames at zero loss must be 0", 0, concealedCount)
        assertTrue("Queue depth at zero loss should remain nominal <= 4 (got ${jb.depthFrames})", jb.depthFrames <= 4)
    }

    @Test
    fun jitterBufferSimulation_fivePercentRandomLoss_queueRemainsBounded() {
        var now = 10_000L
        val clock = { now }
        val jb = SourceJitterBuffer("peer", clock = clock)
        val rng = Random(12345L)

        var audioCount = 0
        var concealedCount = 0

        for (seq in 1..100) {
            if (rng.nextInt(100) >= 5) { // 95% arrive, 5% lost
                jb.enqueue(seq, ByteArray(MeshConfig.BYTES_PER_FRAME))
            }
            val frame = jb.pollFrame()
            when (frame) {
                is PlayoutFrame.Audio -> audioCount++
                is PlayoutFrame.Concealed -> concealedCount++
                else -> {}
            }
            now += 20L
        }

        assertTrue("Audio frames played should be roughly 90-95", audioCount in 88..95)
        assertTrue("Concealed frames should account for dropped packets", concealedCount in 3..10)
        assertTrue("Queue depth under 5% loss must not grow unboundedly (got ${jb.depthFrames})", jb.depthFrames <= 6)
    }

    @Test
    fun jitterBufferSimulation_burstLoss_gapJumpPreventsStandingQueue() {
        var now = 10_000L
        val clock = { now }
        val jb = SourceJitterBuffer("peer", clock = clock)

        // 1. Initial 20 frames arrive normally
        for (seq in 1..20) {
            jb.enqueue(seq, ByteArray(MeshConfig.BYTES_PER_FRAME))
            jb.pollFrame()
            now += 20L
        }
        val depthBeforeBurst = jb.depthFrames
        assertTrue("Depth before burst should be target depth (got $depthBeforeBurst)", depthBeforeBurst <= 4)

        // 2. Wi-Fi stall: 10 frames lost (seq 21..30)
        for (seq in 21..30) {
            // Frame is lost on wire, pollFrame still called every 20ms tick
            jb.pollFrame()
            now += 20L
        }

        // 3. Wi-Fi recovers: packets resume arriving starting at seq 31
        // After burst resumption, gap jump logic prevents frames from piling up into a 320ms standing queue.
        for (seq in 31..40) {
            jb.enqueue(seq, ByteArray(MeshConfig.BYTES_PER_FRAME))
            jb.pollFrame()
            now += 20L
        }

        // Verify that after resumption, queue depth returns to target depth <= 4 within 3-10 frames
        val depthAfterResumption = jb.depthFrames
        assertTrue(
            "After burst resumption, queue depth must return to nominal target depth <= 4 without standing queue (got $depthAfterResumption)",
            depthAfterResumption <= 4
        )
    }
}
